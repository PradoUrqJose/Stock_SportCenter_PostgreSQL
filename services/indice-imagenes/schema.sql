CREATE TABLE IF NOT EXISTS images (
  code TEXT PRIMARY KEY, key TEXT NOT NULL, etag TEXT NOT NULL DEFAULT '',
  size INTEGER NOT NULL DEFAULT 0, modified TEXT,
  present INTEGER NOT NULL DEFAULT 0, thumb600 INTEGER NOT NULL DEFAULT 0,
  thumb1200 INTEGER NOT NULL DEFAULT 0, checked_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS images_present_code ON images(present, code);
CREATE TABLE IF NOT EXISTS state (
  id INTEGER PRIMARY KEY CHECK(id=1), ready INTEGER NOT NULL DEFAULT 0,
  last_scan TEXT, updated_at TEXT, last_error TEXT,
  scan_id TEXT, lock_until INTEGER NOT NULL DEFAULT 0
);
INSERT OR IGNORE INTO state(id) VALUES(1);
CREATE TABLE IF NOT EXISTS scan_images (
  scan_id TEXT NOT NULL, code TEXT NOT NULL, key TEXT NOT NULL, etag TEXT NOT NULL,
  size INTEGER NOT NULL, modified TEXT NOT NULL, thumb600 INTEGER NOT NULL,
  thumb1200 INTEGER NOT NULL, PRIMARY KEY(scan_id, code)
);
